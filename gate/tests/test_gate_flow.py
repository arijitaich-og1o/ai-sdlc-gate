def test_prechecks_catch_secrets_and_env_files(cfg):
    cs = ChangeSet(
        files=[
            ChangedFile(path="settings.py", status="A", content='DB_PASSWORD = "Sup3rS3cretPr0d!"\nx = 1\n'),  # sdlc-gate: allow-secret (test fixture)
            ChangedFile(path="keys.txt", status="A", content="ghp_" + "a" * 40 + "\n"),
            ChangedFile(path=".env", status="A", content="A=b\n"),
            ChangedFile(path=".env.example", status="A", content="A=<YOUR_KEY>\n"),
            ChangedFile(path="ok.py", status="A", content='PASSWORD = "<YOUR_PASSWORD>"\n'),
        ]
    )
    findings = run_prechecks(cfg, cs)
    files = sorted(f["file"] for f in findings)
    assert files == [".env", "keys.txt", "settings.py"]
    assert all(f["severity"] == "blocker" for f in findings)



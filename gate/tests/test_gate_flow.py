# ----------------------------------------------------------------------------- git collection

def test_collect_range_and_staged(cfg, tmp_repo: Path):
    (tmp_repo / "app.py").write_text("print('hi')\n", encoding="utf-8")
    git("add", ".", cwd=tmp_repo)
    staged = collect_staged(cfg, tmp_repo)
    assert staged.paths == ["app.py"] and staged.files[0].status == "A" and "print" in staged.files[0].diff

    git("commit", "-q", "-m", "feat: add app\n\nSDLC-Intent: deploy", cwd=tmp_repo)
    (tmp_repo / "package-lock.json").write_text("{}", encoding="utf-8")
    git("add", ".", cwd=tmp_repo)
    git("commit", "-q", "-m", "chore: lock", cwd=tmp_repo)
    cs = collect_range(cfg, "HEAD~2", "HEAD", tmp_repo)
    assert cs.paths == ["app.py"] and cs.excluded == ["package-lock.json"]
    assert any("SDLC-Intent: deploy" in m for m in cs.commit_messages)
    assert detect_intent(cfg, commit_messages=cs.commit_messages, paths=cs.paths).intent == "deploy"


def test_collect_range_root_commit(cfg, tmp_repo: Path):
    cs = collect_range(cfg, None, "HEAD", tmp_repo)
    assert cs.paths == ["README.md"] and cs.base is None



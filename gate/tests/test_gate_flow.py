def _finding(sev="high", cat="sql-injection", title="SQL built by f-string", file="app.py", line=10):
    return {"id": f"{cat}-{line}", "severity": sev, "category": cat, "title": title, "description": "d", "file": file, "line": line, "recommendation": "r", "confidence": 0.9}


def responder_with(findings):
    return lambda system, user: {"summary": "ok", "findings": findings}


# ----------------------------------------------------------------------------- helpers

def test_extract_json_tolerates_fences_and_prose():
    assert extract_json('```json\n{"a": 1}\n```') == {"a": 1}
    assert extract_json('Sure! {"a": [1,2]} done') == {"a": [1, 2]}


def test_normalize_findings_coerces_and_sorts():
    raw = [
        {"title": "x", "severity": "CRITICAL", "category": "SQL Injection", "line": "12", "confidence": "0.4"},
        {"title": "y", "severity": "warning", "category": "general"},
        {"no_title": True},
        "garbage",
    ]
    out = normalize_findings(raw, phase=4)
    assert [f["severity"] for f in out] == ["blocker", "medium"]
    assert out[0]["category"] == "sql-injection" and out[0]["line"] == 12 and out[0]["phase"] == 4


def test_matches_any_globs():
    assert matches_any("package-lock.json", ["**/package-lock.json"])
    assert matches_any("web/dist/app.js", ["**/dist/**"])
    assert matches_any("dist/app.js", ["**/dist/**"])
    assert not matches_any("src/app.py", ["**/*.lock"])


def test_chunking_respects_budget():
    cs = ChangeSet(files=[ChangedFile(path=f"f{i}.py", status="M", diff="x" * 1000) for i in range(10)])
    chunks = chunk_changeset(cs, 2500)
    assert len(chunks) == 5 and all(len(c.files) == 2 for c in chunks)



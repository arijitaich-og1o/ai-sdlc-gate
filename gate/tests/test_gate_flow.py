# ----------------------------------------------------------------------------- skip

def test_skip_requires_reason_and_valid_phases(cfg):
    ok = parse_skip(cfg, ["fix\n\nSDLC-Skip: 5\nSDLC-Skip-Reason: Test suite is being rewritten under PAY-1432; this commit only moves files."])
    assert ok.valid and ok.valid_phases == [5]
    short = parse_skip(cfg, ["SDLC-Skip: 5\nSDLC-Skip-Reason: too short"])
    assert not short.valid and any("at least 40" in e for e in short.errors)
    bad_phase = parse_skip(cfg, ["SDLC-Skip: 9\nSDLC-Skip-Reason: " + "x" * 50])
    assert not bad_phase.valid
    none = parse_skip(cfg, ["just a commit"])
    assert not none.requested


def test_skip_of_deploy_phase_approval_policy(cfg):
    from sdlc_gate.config import Config

    texts = ["SDLC-Skip: 6\nSDLC-Skip-Reason: Deployment manifests are generated by the platform team in PLAT-88; nothing to review here."]
    allowed = parse_skip(cfg, texts)  # repository policy: no reviewer exists at commit time
    assert allowed.valid and allowed.valid_phases == [6]
    strict = Config()
    strict.data["skip"]["require_approval_for_phases"] = [6, 7]
    denied = parse_skip(strict, texts)
    assert not denied.valid and any("sdlc-skip-approved" in e for e in denied.errors)
    approved = parse_skip(strict, texts, approved_phases=[6, 7])
    assert approved.valid and approved.valid_phases == [6]


def test_skip_reason_may_fold_over_lines(cfg):
    req = parse_skip(cfg, ["SDLC-Skip: 4, 5\nSDLC-Skip-Reason: first part of the reason that is long enough\n  continued on the next line with ticket ABC-1"])
    assert req.valid and req.valid_phases == [4, 5] and "continued" in req.reason


# ----------------------------------------------------------------------------- run_gate

def _run(cfg, skills, findings, texts=None, approved=None, intent="commit"):
    cs = ChangeSet(files=[ChangedFile(path="app.py", status="M", diff="+x", content="x")], commit_messages=texts or [])
    it = detect_intent(cfg, explicit=intent)
    skip = parse_skip(cfg, texts or [], approved_phases=approved)
    llm = StaticLLM(responder_with(findings))
    return run_gate(cfg, llm, skills, cs, it, skip, context={"repo": "org/x", "actor": "dev1"})


def test_gate_passes_with_only_low_findings(cfg, skills_dir):
    skills = load_skills(skills_dir, cfg)
    report = _run(cfg, skills, [_finding(sev="low"), _finding(sev="medium", cat="dead-code")])
    assert report.verdict == "pass"
    assert [p.phase for p in report.phases] == [3, 4, 5]
    assert MARKER in to_markdown(report)


def test_gate_fails_on_high_finding(cfg, skills_dir):
    skills = load_skills(skills_dir, cfg)
    report = _run(cfg, skills, [_finding(sev="high")])
    assert report.verdict == "fail"
    assert all(p.verdict == "fail" for p in report.phases)
    md = to_markdown(report)
    assert "SDLC Gate: FAIL" in md and "SDLC-Skip-Reason" in md


def test_valid_skip_waives_findings_but_not_secrets(cfg, skills_dir):
    skills = load_skills(skills_dir, cfg)
    texts = ["SDLC-Skip: 3,4,5\nSDLC-Skip-Reason: Prototype branch for spike SPK-12; will be rewritten before it reaches develop."]
    report = _run(cfg, skills, [_finding(sev="high")], texts=texts)
    assert report.verdict == "pass"
    assert all(p.verdict == "waived" for p in report.phases)
    assert all(f["waived"] for p in report.phases for f in p.findings)

    leaked = _run(cfg, skills, [_finding(sev="blocker", cat="hardcoded-credential", title="key")], texts=texts)
    assert leaked.verdict == "fail"
    assert all(not f["waived"] for p in leaked.phases for f in p.findings)


def test_gate_fails_closed_on_model_error(cfg, skills_dir):
    from sdlc_gate.llm import LLMError

    skills = load_skills(skills_dir, cfg)

    def boom(system, user):
        raise LLMError("proxy down")

    cs = ChangeSet(files=[ChangedFile(path="app.py", status="M", diff="+x", content="x")])
    report = run_gate(cfg, StaticLLM(boom), skills, cs, detect_intent(cfg, explicit="commit"), parse_skip(cfg, []))
    assert report.verdict == "fail"
    assert all(p.verdict == "error" for p in report.phases)



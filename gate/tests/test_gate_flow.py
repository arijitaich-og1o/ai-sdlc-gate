def test_metrics_event_ingest_and_dashboard(cfg, skills_dir, tmp_path):
    skills = load_skills(skills_dir, cfg)
    reports = [
        _run(cfg, skills, [_finding(sev="high")]),
        _run(cfg, skills, []),
        _run(cfg, skills, [_finding(sev="high")], texts=["SDLC-Skip: 3,4,5\nSDLC-Skip-Reason: Legacy module scheduled for deletion in LEG-9; findings are in code that is being removed."]),
    ]
    events_dir = tmp_path / "events"
    for r in reports:
        ev = build_event(r)
        assert validate_event(ev) == []
        path, written = ingest_event(ev, events_dir)
        assert written and path.suffix == ".jsonl"
        _, again = ingest_event(ev, events_dir)
        assert not again  # idempotent
    events = load_events(events_dir)
    assert len(events) == 3
    summary = summarize(events)
    org = summary["organisation"]
    assert org["runs"] == 3 and org["blocked"] == 1 and org["flagged"] == 2
    assert org["skips_requested"] == 1 and org["skips_granted"] == 1
    dev = summary["developers"]["@dev1"]
    assert dev["runs"] == 3 and dev["waived_findings"] == 3  # one waived finding per skipped phase
    assert "org/x" in summary["repositories"]


def test_invalid_events_are_rejected(tmp_path):
    bad = {"schema": 1, "id": "not-a-uuid", "ts": "2026-01-01T00:00:00+00:00", "repo": "x", "actor": "a b", "verdict": "maybe", "intent": "commit", "phases": []}
    errors = validate_event(bad)
    assert len(errors) >= 3
    try:
        ingest_event(bad, tmp_path)
    except ValueError:
        pass
    else:
        raise AssertionError("invalid event was ingested")


